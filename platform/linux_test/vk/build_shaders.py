#!/usr/bin/env python3
"""Compile the Vulkan renderer's GLSL (platform/linux_test/vk/*) to SPIR-V with glslangValidator and write vk_spv.h:
one `static const uint32_t spv_<name>[]` per program.  usage: build_shaders.py <out header>"""
import os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PROGRAMS = [  # name, source, defines
    ('hw_vert', 'hw.vert', []), ('main_vert', 'main.vert', []), ('shadow_vert', 'shadow.vert', []),
    ('fill_vert', 'fill.vert', []), ('fill_frag', 'fill.frag', []), ('present_vert', 'present.vert', []),
    ('present_frag', 'present.frag', []), ('fxaa_frag', 'fxaa.frag', []),
    ('basic_frag', 'main.frag', ['BASIC']), ('fx_frag', 'main.frag', ['FX']), ('fxrt_frag', 'main.frag', ['FX', 'RT']),
]

def main():
    out = sys.argv[1]
    lines = ['/* generated by platform/linux_test/vk/build_shaders.py - do not edit */', '#include <stdint.h>']
    with tempfile.TemporaryDirectory() as tmp:
        for name, src, defs in PROGRAMS:
            spv = os.path.join(tmp, name + '.spv')
            cmd = ['glslangValidator', '-V', '--target-env', 'vulkan1.2', '-I' + HERE] + ['-D' + d for d in defs] + [os.path.join(HERE, src), '-o', spv]
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode:
                sys.stderr.write(r.stdout + r.stderr); sys.exit('shader %s failed' % name)
            data = open(spv, 'rb').read()
            words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
            body = ','.join('0x%08x' % w for w in words)
            lines.append('static const uint32_t spv_%s[] = {%s};' % (name, body))
    open(out, 'w').write('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main()
