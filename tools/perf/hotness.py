#!/usr/bin/env python3
"""Make src/game/hotness.h from a PS Vita profile (prof_vita.txt of the profiling build) and that build's ELF.

Every game function the profile saw running for at least --min samples (inclusive) is declared hot: GCC puts hot functions in .text.hot,
which the linker gathers at the start of the program, so the code a match runs sits together instead of spread over the 10 MB of game
code (the Cortex-A9 has a 32 KB instruction cache).  The profile's addresses are the running program's: --offset is what to subtract
(found automatically: the shift that makes the most addresses land on function starts).

usage: hotness.py prof_vita.txt swbfrs.elf [--min N] [--nm arm-vita-eabi-nm] > src/game/hotness.h"""
import sys, re, subprocess, collections, argparse
ap = argparse.ArgumentParser(); ap.add_argument('prof'); ap.add_argument('elf'); ap.add_argument('--min', type=int, default=20)
ap.add_argument('--nm', default='/usr/local/vitasdk/bin/arm-vita-eabi-nm'); ap.add_argument('--game_h', default='src/game/game.h')
a = ap.parse_args()
syms = {}
for l in subprocess.run([a.nm, '--defined-only', a.elf], capture_output=True, text=True).stdout.split('\n'):
    p = l.split()
    if len(p) == 3 and p[1] in 'tTwW': syms.setdefault(int(p[0], 16) | 1, p[2])
rows = [l.split() for l in open(a.prof) if not l.startswith('#') and l.strip()]
addrs = [int(r[1], 16) for r in rows]
starts = sorted(syms)
c = collections.Counter()
for x in addrs[:400]:
    for s in starts:
        d = x - s
        if -0x400000 < d < 0x400000: c[d] += 1
off = c.most_common(1)[0][0]
incl = collections.Counter()
for r in rows:
    n = syms.get(int(r[1], 16) - off)
    if n: incl[n.replace('__orig', '')] = max(incl[n.replace('__orig', '')], int(r[3]))
hot = {n for n, v in incl.items() if v >= a.min and n.startswith('func_')}
protos = {}
for l in open(a.game_h):
    m = re.match(r'^(.+ (func_[0-9A-F]{8})\(.*\));\s*$', l)
    if m: protos[m.group(2)] = m.group(1)
out = ['/* Generated by tools/perf/hotness.py from a PS Vita profile: the game functions a match runs, declared hot (placed together in',
       ' * .text.hot).  RS_NO_HOTNESS leaves them where they are. */', '#pragma once', '#ifndef RS_NO_HOTNESS']
n = 0
for f in sorted(hot):
    if f in protos: out.append(protos[f] + ' __attribute__((hot));'); n += 1
out.append('#endif'); print('\n'.join(out))
print(f'offset {off:#x}: {len(incl)} functions in the profile, {n} declared hot', file=sys.stderr)
