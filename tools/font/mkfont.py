"""Generate platform/common/ui_font.h: an 8-bit alpha glyph atlas (ASCII 32..126) for platform UI text (conversion screen, HUD).
Source font: DejaVu Sans Bold (Bitstream Vera / DejaVu licence: free to use, modify and redistribute; see the header).
usage: mkfont.py <font.ttf> <pixel size> <out.h>"""
import sys
from PIL import Image, ImageDraw, ImageFont
ttf, px, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
f = ImageFont.truetype(ttf, px); asc, desc = f.getmetrics(); lh = asc + desc
glyphs = []
for c in range(32, 127):
    ch = chr(c); l, t, r, b = f.getbbox(ch); adv = int(round(f.getlength(ch)))
    w, h = max(1, r - l), max(1, b - t)
    im = Image.new('L', (w, h), 0); ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255)
    glyphs.append((c, im, l, t, adv))
W = 512; x = y = 0; rowh = 0; place = []
for c, im, l, t, adv in glyphs:
    if x + im.width + 1 > W: x = 0; y += rowh + 1; rowh = 0
    place.append((c, x, y, im, l, t, adv)); x += im.width + 1; rowh = max(rowh, im.height)
H = 1
while H < y + rowh + 1: H *= 2
atlas = Image.new('L', (W, H), 0)
for c, x, y, im, l, t, adv in place: atlas.paste(im, (x, y))
with open(out, 'w') as o:
    o.write('/* Generated by tools/font/mkfont.py from DejaVu Sans Bold, %d px.  DejaVu fonts: derived from Bitstream Vera\n' % px)
    o.write(' * (Copyright (c) 2003 Bitstream, Inc.; DejaVu changes are in the public domain), free to use and redistribute. */\n#pragma once\n#include <stdint.h>\n')
    o.write('#define UI_FONT_W %d\n#define UI_FONT_H %d\n#define UI_FONT_LINE %d\n#define UI_FONT_ASC %d\n' % (W, H, lh, asc))
    o.write('typedef struct { uint16_t x, y; uint8_t w, h; int8_t ox, oy; uint8_t adv; } ui_glyph_t;\n')
    o.write('static const ui_glyph_t ui_font_glyphs[95] = {\n')
    for c, x, y, im, l, t, adv in place: o.write('  {%d,%d,%d,%d,%d,%d,%d},\n' % (x, y, im.width, im.height, l, t, adv))
    o.write('};\nstatic const uint8_t ui_font_alpha[%d] = {\n' % (W * H))
    d = atlas.tobytes()
    for i in range(0, len(d), 32): o.write(','.join(str(b) for b in d[i:i + 32]) + ',\n')
    o.write('};\n')
print('atlas %dx%d line %d' % (W, H, lh))
