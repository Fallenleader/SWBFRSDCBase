#!/usr/bin/env bash
# Wii U (Aroma) build of Aurek: devkitPPC + wut, GX2 renderer, shaders compiled offline by CafeGLSL's glslcompiler.
#   DEVKITPRO=/opt/devkitpro CAFEGLSL=<glslcompiler binary> engine/platform/wiiu/build.sh   ->  build/wiiu/aurek.rpx, aurek.wuhb
# Copy aurek.wuhb to sd:/wiiu/apps/ (or aurek.rpx to sd:/wiiu/apps/Aurek/); settings.txt and the game files go to
# sd:/wiiu/apps/Aurek.  devkitPPC and wut: devkitPro's packages, or built from devkitPro/buildscripts and devkitPro/wut.
set -euo pipefail
here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
engine=$(cd -- "$here/../.." && pwd)
repo=$(dirname "$engine")
DKP=${DEVKITPRO:-/opt/devkitpro}
export PATH="$DKP/devkitPPC/bin:$DKP/tools/bin:$PATH"
glslc=${CAFEGLSL:?set CAFEGLSL to the CafeGLSL glslcompiler}
out="$repo/build/wiiu"; mkdir -p "$out/obj" "$out/gen"

# shaders: one .gsh per program (vertex + fragment), embedded
hdr="$out/gen/gfx_gx2_gsh.h"; echo "/* generated by platform/wiiu/build.sh - do not edit */" > "$hdr"
for pr in opaque:ak.vert:opaque.frag cutout:ak.vert:cutout.frag alpha:ak.vert:alpha.frag beam:ak.vert:beam.frag ui:ui.vert:ui.frag; do
  IFS=: read -r n vs fs <<<"$pr"
  "$glslc" -vs "$here/shaders/$vs" -ps "$here/shaders/$fs" -o "$out/gen/$n.gsh"
  python3 -c 'import sys; d=open(sys.argv[1],"rb").read(); print("static const unsigned char gsh_%s[] __attribute__((aligned(64))) = {%s};" % (sys.argv[2], ",".join(str(x) for x in d)))' "$out/gen/$n.gsh" "$n" >> "$hdr"
done

# every optimisation flag (GCC: the Vita's set without the ARM ones) for the Espresso (PowerPC 750CL-class)
OPT=(-O3 -mcpu=750 -meabi -mhard-float -DESPRESSO -fomit-frame-pointer -ffast-math -fno-finite-math-only -fno-math-errno -ffp-contract=fast
     -fno-signed-zeros -fno-trapping-math -funroll-loops -ftree-vectorize -fpredictive-commoning -fgcse-after-reload -ftree-loop-distribution
     -floop-nest-optimize -fgraphite-identity -fipa-pta -fipa-cp-clone -fsched-pressure -fno-semantic-interposition -fmerge-all-constants
     -fno-common -fno-stack-protector -ffunction-sections -fdata-sections -flto=auto -flto-partition=one -fuse-linker-plugin)
INC=(-I "$engine" -I "$out/gen" -I "$DKP/wut/include" -isystem "$DKP/wut/include")
build_id=$(git -C "$engine" describe --always --dirty=+ 2>/dev/null || echo unknown)
src=$(grep -o 'add_library(akcore STATIC [^)]*' "$engine/CMakeLists.txt" | cut -d' ' -f3-)
src="$src app/viewer.c app/play.c app/play_sound.c app/hud.c app/frontend.c app/gc_screen.c video/ak_movie.c platform/desktop/plat_desktop.c platform/wiiu/plat_wiiu.c platform/wiiu/gfx_gx2.c"
objs=()
for f in $src; do
  o="$out/obj/$(echo "$f" | tr / _).o"; extra=()
  [[ $f == game/ak_gc_ai.c ]] && extra=(-fno-fast-math -ffp-contract=off)   # the GC AI rounds as the PSP does
  powerpc-eabi-gcc -std=gnu11 "${OPT[@]}" "${extra[@]}" -D__WIIU__ -D__WUT__ -DAK_BUILD_ID="\"$build_id\"" "${INC[@]}" \
     -Wall -Wno-unused-parameter -Wno-missing-field-initializers -c "$engine/$f" -o "$o"
  objs+=("$o")
done
powerpc-eabi-gcc "${OPT[@]}" -specs="$DKP/wut/share/wut.specs" -Wl,--gc-sections -o "$out/aurek.elf" "${objs[@]}" \
  -L "$DKP/wut/lib" -lwut -lm
elf2rpl "$out/aurek.elf" "$out/aurek.rpx"
wuhbtool "$out/aurek.rpx" "$out/aurek.wuhb" --name "Aurek" --short-name "Aurek" --author "Aurek" \
  ${AK_WIIU_ICON:+--icon="$AK_WIIU_ICON"}
cp "$here/settings.txt" "$out/settings.txt"
ls -la "$out"/aurek.rpx "$out"/aurek.wuhb
