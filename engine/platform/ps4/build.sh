#!/usr/bin/env bash
# PS4 build of Aurek: OpenOrbis toolchain + PS4GL_GNM (GNM renderer, shaders compiled here on the PC).
#   OO_PS4_TOOLCHAIN=<toolchain> PS4GL=<PS4GL_GNM checkout> engine/platform/ps4/build.sh  ->  build/ps4/IV0000-AURK00001_00-AUREKENGINE00000.pkg
# The toolchain: an OpenOrbis release, or bootstrap_toolchain.sh (from git) - its libc++.a must hold libc++abi and libunwind too
# (the release's does; the bootstrap merges them).  PS4GL_GNM needs LLVM with the AMDGPU target on PATH (clang, llc, opt, llvm-link,
# llvm-objcopy, llvm-mc) and Python 3; the package needs .NET for PkgTool.Core.  Install with GoldHEN's package installer.
set -euo pipefail
here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
engine=$(cd -- "$here/../.." && pwd)
repo=$(dirname "$engine")
tc=${OO_PS4_TOOLCHAIN:?set OO_PS4_TOOLCHAIN}
gl=${PS4GL:?set PS4GL to the PS4GL_GNM checkout}
out="$repo/build/ps4"
mkdir -p "$out/obj" "$out/gen" "$out/sb"

# shaders: GLSL ES -> PS4 shader binaries (PS4GL's compiler) -> one header
hdr="$out/gen/gfx_ps4_sb.h"; echo "/* generated by platform/ps4/build.sh - do not edit */" > "$hdr"
for f in "$here"/shaders/*.vert "$here"/shaders/*.frag; do
  b=$(basename "$f"); python3 "$gl/tools/shadersbC.py" "$f" -o "$out/sb/$b.sb" >/dev/null
  python3 -c 'import sys; d=open(sys.argv[1],"rb").read(); print("static const unsigned char sb_%s[] = {%s};" % (sys.argv[2].replace(".","_"), ",".join(str(x) for x in d)))' "$out/sb/$b.sb" "$b" >> "$hdr"
done

# every optimisation flag clang has for the PS4's Jaguar cores (btver2); GCC-only ones (graphite, IPA-PTA) have no clang form
OPT=(-O3 -march=btver2 -mtune=btver2 -ffast-math -fno-finite-math-only -fno-math-errno -ffp-contract=fast -fno-signed-zeros
     -fno-trapping-math -funroll-loops -fvectorize -fslp-vectorize -fomit-frame-pointer -fno-semantic-interposition
     -fmerge-all-constants -fno-common -fno-stack-protector -ffunction-sections -fdata-sections)
BASE=(--target=x86_64-pc-freebsd12-elf -fPIC -funwind-tables -D_GNU_SOURCE -isysroot "$tc" -isystem "$tc/include")
build_id=$(git -C "$engine" describe --always --dirty=+ 2>/dev/null || echo unknown)
src=$(grep -o 'add_library(akcore STATIC [^)]*' "$engine/CMakeLists.txt" | cut -d' ' -f3-)
src="$src app/viewer.c app/play.c app/play_sound.c app/hud.c app/frontend.c app/gc_screen.c platform/desktop/plat_desktop.c platform/ps4/plat_ps4.c platform/ps4/gfx_ps4gl.c"
objs=()
for f in $src; do
  o="$out/obj/$(echo "$f" | tr / _).o"; extra=()
  [[ $f == game/ak_gc_ai.c ]] && extra=(-fno-fast-math -ffp-contract=off)   # the GC AI rounds as the PSP does
  clang "${BASE[@]}" -std=gnu11 "${OPT[@]}" "${extra[@]}" -DAK_BUILD_ID="\"$build_id\"" -I "$engine" -I "$out/gen" -I "$gl/include" \
     -Wall -Wno-unused-parameter -Wno-missing-field-initializers -c "$engine/$f" -o "$o"
  objs+=("$o")
done
# the driver (its own flags: C++17, as PS4GL builds it) and its malloc on direct memory
clang++ "${BASE[@]}" -std=c++17 -O3 -march=btver2 -isystem "$tc/include/c++/v1" -I "$gl/include" -I "$gl/src" -I "$gl/src/gen" -c "$gl/src/ps4gl.cpp" -o "$out/obj/ps4gl.o"
clang "${BASE[@]}" -O3 -march=btver2 -w -I "$gl/include" -I "$gl/src" -c "$gl/src/ps4gl_heap.c" -o "$out/obj/ps4gl_heap.o"
ld.lld -m elf_x86_64 -pie --script "$tc/link.x" --eh-frame-hdr --gc-sections -O2 -o "$out/aurek.elf" -L"$tc/lib" \
  "${objs[@]}" "$out/obj/ps4gl.o" "$out/obj/ps4gl_heap.o" \
  -lc -lkernel -lc++ -lSceSysmodule -lSceSystemService -lSceVideoOut -lSceGnmDriver -lScePad -lSceUserService -lSceAudioOut "$tc/lib/crt1.o"
python3 "$gl/tools/mkpkg.py" "$out/aurek.elf" --title "Aurek" --title-id AURK00001 --label AUREKENGINE --version 01.00 \
  --icon "$repo/platform/ps5/sce_sys/icon0.png" -o "$out"
cp "$here/settings.txt" "$out/settings.txt"
ls -la "$out"/*.pkg
