"""Generates render/ak_font.h: ASCII 32..126 from DejaVu Sans Mono (Bitstream Vera licence: embedding allowed), 8x16 cells,
a 128x96 8-bit alpha atlas (16 x 6 glyphs).  Run: python3 tools/gen/mkfont.py <DejaVuSansMono.ttf> > render/ak_font.h"""
import sys
from PIL import Image, ImageDraw, ImageFont
f = ImageFont.truetype(sys.argv[1], 13)
W, H = 8, 16; img = Image.new('L', (16 * W, 6 * H), 0); d = ImageDraw.Draw(img)
for c in range(32, 127):                     # each glyph drawn in its own cell image, so nothing spills into its neighbours
    i = c - 32; g = Image.new('L', (W, H), 0); ImageDraw.Draw(g).text((0, 1), chr(c), fill=255, font=f)
    img.paste(g, ((i % 16) * W, (i // 16) * H))
px = img.tobytes()
print('/* generated by tools/gen/mkfont.py from DejaVu Sans Mono (Bitstream Vera licence). ASCII 32..126, 8x16 cells, 16 per row. */')
print('#ifndef AK_FONT_H\n#define AK_FONT_H\n#define AK_FONT_W 128\n#define AK_FONT_H_PX 96\n#define AK_FONT_CW 8\n#define AK_FONT_CH 16')
print('static const unsigned char ak_font_alpha[%d] = {' % len(px))
for k in range(0, len(px), 32): print('  ' + ','.join(str(b) for b in px[k:k + 32]) + ',')
print('};\n#endif')
